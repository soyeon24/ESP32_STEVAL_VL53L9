#pragma once

// ---------------------------------------------------------------------------
// ESP32 DevKit v1  <->  STEVAL-VL53L9 (VL53L9CX) 배선 설정
//
// 근거: STEVAL-VL53L9 Data brief DB5805 Rev 1 (2026-03) 회로도
//
// J2 헤더(8핀, 2.54mm)의 신호선:
//     3V3 / SYNC_IN / AP_CLK / INTR / XSHUT / SCL / SDA / GND
//
// 보드 특성:
//   * 3V3 만 넣으면 온보드 LDO 가 2V8 / 1V8 / 1V2 를 만든다.
//   * U1/U2 (PI4ULS3V204) 레벨 시프터가 호스트 <-> 센서(1.8V) 사이에 있다.
//   * J3 점퍼가 HOST_IOVDD 를 3V3 / 1V8 중에서 고른다. --> 반드시 3V3!
//   * R7/R8 = 2.2k 풀업이 호스트 쪽 SDA/SCL 에 이미 있다. 외부 풀업 금지.
//   * Y1 = 12MHz 온보드 발진기가 "실장되어" 있다. 다만 기본 상태에서는
//     동작하지 않는다. 아래 "클럭 소스" 항목을 반드시 읽을 것.
// ---------------------------------------------------------------------------

// --- I2C ---
#define PIN_SDA        21
#define PIN_SCL        22

// 브링업 단계에서는 느리게 시작한다. 안정 확인 후 400k 로 올릴 것.
#define I2C_FREQ_HZ    100000UL

// --- I2C 주소 (회로도에 명시된 값) ---
#define TOF_I2C_ADDR_7BIT     0x29   // VL53L9CX     (8-bit 0x52)
#define EEPROM_I2C_ADDR_7BIT  0x55   // M24C64 (U4)  (8-bit 0xAA)

// --- 제어 핀 ---
// 연결하지 않은 핀은 -1 로 두면 코드가 건너뛴다.
#define PIN_XSHUT      32   // 필수. LOW = 셧다운, HIGH = 동작
#define PIN_INTR       27   // 입력. 측정 완료 인터럽트
#define PIN_SYNC_IN    -1   // 다중 센서 동기화용. 단독 사용이면 불필요
#define PIN_AP_CLK     -1   // 온보드 Y1 을 쓰므로 호스트 클럭 불필요. 아래 참고.

// ---------------------------------------------------------------------------
// 클럭 소스 (R23 / R24 / R25) -- 이걸 틀리면 센서가 I2C 에 전혀 응답하지 않는다
//
// 센서 AP_CLK(U3 pin E11) 에는 두 소스가 같은 노드로 들어온다. 하나만 고른다.
//
//     J2 AP_CLK ──[R23 0R]──┬── U3 E11 (AP_CLK)
//                           │
//     Y1 OUT ────[R24 0R]───┘
//
// 그리고 Y1 의 OE 핀은 R25 를 통해 GND 로 내려간다.
//
//     Y1 pin1 (OE) ──[R25 0R]── GND
//
// 스키매틱 노트 원문: "Fit OE resistor to disable oscillator."
//
//   R25 장착  -> OE 가 GND 에 묶임        -> 발진기 정지
//   R25 제거  -> OE 플로팅 (내부 풀업)    -> 발진기 동작
//
// >>> 온보드 발진기를 쓰려면:  R25 제거 / R24 장착 / R23 제거 <<<
//
// 주의: R25 가 장착된 상태에서는 전원, XSHUT, 레벨시프터가 전부 정상이어도
//       센서 코어가 부팅하지 못해 어떤 주소에도 ACK 하지 않는다. 실제로
//       이 증상으로 오래 헤맸다. 응답이 없으면 R25 부터 확인할 것.
// ---------------------------------------------------------------------------

// --- 시리얼 ---
#define SERIAL_BAUD    115200

// EEPROM(U4, M24C64) 에는 모듈 캘리브레이션 데이터가 들어 있을 수 있다.
// 이 스케치는 절대 쓰기를 하지 않는다. 읽기 전용으로만 접근할 것.
//
// 위치 주의: U4 는 VCC=P1V8 이고 SCL/SDA 가 센서와 같은 1.8V 버스에 붙어 있다.
// 즉 레벨시프터 "안쪽"이다. 따라서 0x55 가 응답하면 시프터가 I2C 를 통과시킨다는
// 뜻이라, 버스 정상 여부를 가리는 좋은 기준점이 된다.
//
// 단, 현재 실험 보드에서는 U4 가 물리적으로 제거되어 있어 0x55 는 응답하지 않는다.
